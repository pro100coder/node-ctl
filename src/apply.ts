// apply: Terraform once per account, in its provider's root and workspace, then what follows from the
// inventory on this computer (~/.ssh/config.d/node-ctl). Used by init and accounts add to register
// the ssh key with a new account, and by every command that edits the inventory; the apply command
// (machine.ts) adds the machine sync.
import { mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { accounts, account, type Config } from './config.ts';
import * as contabo from './contabo.ts';
import { UserError } from './errors.ts';
import { editMachine, ensureAccounts, machineNames, readMachine } from './inventory.ts';
import { ActionFailure, type Progress } from './progress/progress.ts';
import { addr } from './ssh.ts';
import { tfAccount, tfInit } from './terraform.ts';

type Env = Record<string, string | undefined>;
interface Where {
  servers: string;
  home: string;
  sshConfig: string;
}

// A step whose child process failed fails, and so does the step around it, both with the exit status.
async function step(progress: Progress, name: string, key: string, run: () => Promise<{ status: number }>): Promise<void> {
  const ok = await progress.withAction(name, key, async () => {
    const r = await run();
    if (r.status !== 0) throw new ActionFailure('', r.status);
  });
  if (!ok) throw new ActionFailure('', 1);
}

// Contabo refuses a firewall (402) until its instance has finished provisioning, and the provider leaves
// the firewall it created behind, so the next apply fails on the name (409). A machine whose firewall
// Terraform does not hold yet gets its instance on its own first, then its firewall in the full apply
// once Contabo reports the instance up; machines that have one cost nothing extra.
async function contaboInstancesFirst(config: Config, at: Where, progress: Progress, env: Env, tag: string): Promise<void> {
  const tf = { config, home: at.home, servers: at.servers, progress, env };
  const state = await tfAccount({ ...tf, capture: true }, tag, ['state', 'list']);
  const have = new Set(state.status === 0 ? state.stdout.split('\n') : []);
  const waits = machineNames(at.servers).filter((name) => {
    const m = readMachine(at.servers, name);
    return m.account === tag && m.state !== 'archived' && !have.has(`contabo_firewall.dev["${name}"]`);
  });
  if (!waits.length) return;
  const targets = waits.map((name) => `-target=contabo_instance.dev["${name}"]`);
  await step(progress, `terraform apply (${tag}, instances)`, 'apply', () =>
    tfAccount(tf, tag, ['apply', '-input=false', '-no-color', '-auto-approve', ...targets]),
  );
  for (const name of waits) {
    await step(progress, `Wait for the ${name} instance`, 'wait', () =>
      contabo.waitInstance(env, config.contabo[tag]!, name).then(
        () => ({ status: 0 }),
        (e: unknown) => {
          progress.log(e instanceof Error ? e.message : String(e), 'stderr');
          return { status: 1 };
        },
      ),
    );
  }
}

// do_apply: what the Apply Terraform step runs; resize runs it alone, to undo its edit when it fails.
export async function doApply(config: Config, at: Where, progress: Progress, env: Env): Promise<void> {
  const tf = { config, home: at.home, servers: at.servers, progress, env };
  await step(progress, 'terraform init', 'init', () => tfInit(tf, 'hetzner'));
  if (Object.keys(config.contabo).length) await step(progress, 'terraform init (contabo)', 'init', () => tfInit(tf, 'contabo'));
  for (const tag of accounts(config)) {
    if (account(config, tag)?.provider === 'contabo') await contaboInstancesFirst(config, at, progress, env, tag);
    await step(progress, `terraform apply (${tag})`, 'apply', () => tfAccount(tf, tag, ['apply', '-input=false', '-no-color', '-auto-approve']));
  }
}

// Generated, never merged: plain ssh node-ctl-<name> for every running machine, with the resolved
// tailnet address (MagicDNS may answer nothing on the host) and tssh's host-key stance. The node-ctl-
// prefix keeps the entries from shadowing the user's own.
async function writeSshConfig(servers: string, file: string, env: Env): Promise<void> {
  let text = '# Generated by node-ctl — edits are overwritten. Machines: node-ctl list\n';
  for (const name of machineNames(servers)) {
    if (readMachine(servers, name).state !== 'running') continue;
    text += `\nHost node-ctl-${name}\n  HostName ${await addr(name, env)}\n  User node-ctl-user\n  StrictHostKeyChecking no\n  UserKnownHostsFile /dev/null\n`;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(`${file}.tmp`, text);
  renameSync(`${file}.tmp`, file);
}

export async function updateSshConfig(servers: string, file: string, progress: Progress, env: Env): Promise<void> {
  try {
    await writeSshConfig(servers, file, env);
  } catch {
    progress.warn(`could not write ${file}; node-ctl ssh still works`);
  }
}

export async function apply(config: Config, at: Where, progress: Progress, env: Env, retry = 'node-ctl apply'): Promise<void> {
  ensureAccounts(config, at.servers); // a machine of an unknown account is in no workspace, and no apply would ever see it
  if (!(await progress.withAction('Apply Terraform', 'apply', () => doApply(config, at, progress, env)))) {
    throw new UserError(`terraform apply failed: the inventory is updated, the infrastructure is not; fix the cause, then: ${retry}`);
  }
  for (const name of machineNames(at.servers)) {
    const m = readMachine(at.servers, name);
    // a stopped machine's VPS is gone now: its stop is over
    if (m.state !== 'running' && m.stopping != null) editMachine(at.servers, name, (e) => delete e.stopping);
  }
  await updateSshConfig(at.servers, at.sshConfig, progress, env);
}
